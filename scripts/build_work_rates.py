"""Build knowledge/work_rates.yaml from knowledge/labor_price_lists.yaml.

    uv run python scripts/build_work_rates.py

Per work type: expected = median of the public price lists, low/high = p25/p75 (linear
interpolation). The engine applies one spread to the total, so the global spread is the median
over works of p25/median and p75/median; the per-work quantiles stay in the file. Labelled
"рыночный ориентир, уточняется у Максидом". If the organisers send official rates, replace
`rub_per_unit` and `source` by theirs (docs/OPEN_QUESTIONS.md #8): nothing else changes.
"""
import statistics
from decimal import ROUND_HALF_UP, Decimal
from pathlib import Path

import yaml

KNOW = Path(__file__).resolve().parents[1] / "src" / "maxicalc" / "knowledge"
LABEL = "рыночный ориентир, уточняется у Максидом"


def q(vals: list[int], p: int) -> Decimal:
    if len(vals) == 1:
        return Decimal(vals[0])
    cuts = statistics.quantiles(vals, n=100, method="inclusive")
    return Decimal(str(cuts[p - 1]))


def r0(x: Decimal) -> int:
    return int(x.quantize(Decimal(1), rounding=ROUND_HALF_UP))


# Which works a renovation class includes. A class is NOT a price multiplier: major / designer
# add the structural works (plaster-level prep, screed, waterproofing, drywall, wiring) and the
# tier of the sourced rates rises p25 -> median -> p75.
SCOPE = {
    "cosmetic": ["wallpapering", "painting_walls", "priming", "puttying", "laminate",
                 "skirting", "tiling_floor", "tiling_wall"],
    "major": ["wallpapering", "painting_walls", "priming", "puttying", "laminate", "skirting",
              "tiling_floor", "tiling_wall", "self_leveling", "waterproofing",
              "drywall_lining", "electrical_point"],
    "designer": ["wallpapering", "painting_walls", "priming", "puttying", "laminate", "skirting",
                 "tiling_floor", "tiling_wall", "self_leveling", "waterproofing",
                 "drywall_lining", "electrical_point"],
}


def main() -> None:
    src = yaml.safe_load((KNOW / "labor_price_lists.yaml").read_text(encoding="utf-8"))
    sources = src["sources"]
    rates: dict[str, dict] = {}  # type: ignore[type-arg]
    lows: list[Decimal] = []
    highs: list[Decimal] = []
    for work, w in src["works"].items():
        vals = sorted(p["rub"] for p in w["prices"])
        used = sorted({p["source"] for p in w["prices"]})
        if len(used) < 3:
            raise SystemExit(f"{work}: меньше трёх источников ({len(used)})")
        med = Decimal(str(statistics.median(vals)))
        p25, p75 = q(vals, 25), q(vals, 75)
        lows.append(p25 / med)
        highs.append(p75 / med)
        names = ", ".join(f"{sources[s]['name']} {sources[s]['url']}" for s in used)
        rates[work] = {
            "unit": w["unit"], "rub_per_unit": r0(med), "p25": r0(p25), "p75": r0(p75),
            "n_sources": len(used),
            "source": f"{LABEL}: медиана {len(used)} публичных прайс-листов СПб, "
                      f"прочитаны {sources[used[0]]['checked']} ({names})",
            "values": {p["source"]: p["rub"] for p in w["prices"]},
            "accessed": [{"source": s, "url": sources[s]["url"],
                          "accessed": str(sources[s]["checked"]),
                          "rub": next(p["rub"] for p in w["prices"] if p["source"] == s)}
                         for s in used],
        }
    spread_low = r2(Decimal(str(statistics.median(lows))))
    spread_high = r2(Decimal(str(statistics.median(highs))))
    out = {
        "region_coeff": {"spb": 1},
        "class_tier": {"cosmetic": "p25", "major": "median", "designer": "p75"},
        "scope": SCOPE,
        "spread": {"low": float(spread_low), "high": float(spread_high),
                   "basis": "медиана по видам работ отношений p25/медиана и p75/медиана"},
        "rates": rates,
    }
    header = (
        "# Labor rates, rub per unit, St. Petersburg. GENERATED by scripts/build_work_rates.py\n"
        "# from labor_price_lists.yaml (public price lists, URL + access date per source). Label:\n"
        f"# {LABEL}. No class multipliers: classes differ by `scope` (works included) and\n"
        "# `class_tier` (p25 / median / p75 of the rates). Replace with official rates when the\n"
        "# organisers send them (docs/OPEN_QUESTIONS.md #8).\n")
    (KNOW / "work_rates.yaml").write_text(
        header + yaml.safe_dump(out, allow_unicode=True, sort_keys=False, width=100),
        encoding="utf-8")
    for k, v in rates.items():
        print(f"{k:18} {v['p25']:>5} / {v['rub_per_unit']:>5} / {v['p75']:>5} ({v['n_sources']})")
    print("spread", spread_low, spread_high)


def r2(x: Decimal) -> Decimal:
    return x.quantize(Decimal("0.01"), rounding=ROUND_HALF_UP)


if __name__ == "__main__":
    main()
