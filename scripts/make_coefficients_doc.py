"""Generate docs/COEFFICIENTS.md from knowledge/corrections.yaml and waste_coefficients.yaml.

    uv run python scripts/make_coefficients_doc.py
"""
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
K = ROOT / "src" / "maxicalc" / "knowledge"

HEAD = """# Поправочные коэффициенты

Таблица настраиваемая: **вид работы × материал × условия**. Данные лежат в
`src/maxicalc/knowledge/corrections.yaml` (расход, толщина слоя) и
`waste_coefficients.yaml` (запас по раскладке плитки и ламината); код движка значений не содержит.
Каждое значение имеет публичный источник (URL и цитата), а в расчёте строка `explain` показывает
коэффициент, причину и источник. Условия задаются в запросе: `POST /api/v1/calc/room`, поле
`conditions` (`floor_layout`, `wall_evenness`, `paint_surface`, `paint_layers`,
`plaster_application`). Документ строится скриптом `scripts/make_coefficients_doc.py`.

## 1. Таблица

| вид работы | материал | условие | эффект | значение | причина | источник (вид) |
|---|---|---|---|---|---|---|
"""


def build() -> str:
    corr = yaml.safe_load((K / "corrections.yaml").read_text(encoding="utf-8"))["corrections"]
    waste = yaml.safe_load((K / "waste_coefficients.yaml").read_text(encoding="utf-8"))
    rows = []
    for c in corr:
        cond = ", ".join(f"{k}={v}" for k, v in c["condition"].items())
        s = c["source"]
        rows.append(f"| {c['work']} | {c['material']} | {cond} | {c['effect']['type']} | "
                    f"{c['effect']['value']} | {c['reason']} | [{s['name']}]({s['url']}) "
                    f"({s['kind']}) |")
    for layout, v in waste["layouts"].items():
        rows.append(f"| tile_laying | плитка | floor_layout={layout} | waste_share | {v} | "
                    "запас на подрезку и бой | ответ эксперта организаторов в чате кейса "
                    "(20.10.2026): запас 1,05–1,15 по раскладке; значения команды внутри "
                    "диапазона, точной таблицы эксперт не дал (organizer_expert) |")
    for layout, v in waste["laminate"]["layouts"].items():
        rows.append(f"| laminate_laying | ламинат | floor_layout={layout} | waste_share | {v} | "
                    "запас на подрезку | [Quick-Step: как рассчитать ламинат]"
                    "(https://www.quick-step.ru/blog/raschet-laminata/) (manufacturer): прямая "
                    "5 %, ёлочка 5–10 %, диагональ 15–20 %; взята верхняя граница |")
    rows.append(f"| tile_laying | плитка | площадь < 4 м² | waste_share | "
                f"+{waste['small_room_extra']} | малая площадь: больше подрезки | значение по "
                "умолчанию, без источника |")
    rows.append(f"| tile_laying | плитка | сторона >= 600 мм | waste_share | "
                f"+{waste['large_format_extra']} | крупный формат: больше отходов | значение по "
                "умолчанию, без источника |")
    body = "\n".join(rows)
    scen = """

## 2. Что в таблице подтверждено производителем, а что нет

- Производитель: впитывающее основание для краски (Tikkurila), толщина слоя шпатлёвки
  (Vetonit, Ceresit).
- Выведено нами из двух документов производителя: машинная штукатурка (Knauf MP 75 к Ротбанду),
  оценка порядка величины; лист Ротбанда без расшифровки сноски.
- Источник — эксперт организаторов (чат кейса, 20.10.2026), не производитель: запас на плитку
  1,05–1,15 по раскладке (наши 1,07 / 1,12 / 1,15 внутри диапазона; точной таблицы эксперт не дал).
- Производитель: запас на ламинат — Quick-Step (прямая 5 %, ёлочка 5–10 %, диагональ 15–20 %);
  в таблице верхняя граница (5 / 10 / 20 %). Инструкции Kronopol и Skalla процентов не содержат.
- **Выведено** (derived): множитель машинной штукатурки 1,18 = 10 кг/м² (КНАУФ-МП 75, слой 10 мм)
  / 8,5 кг/м² (КНАУФ-Ротбанд, слой 10 мм) = 1,176; два разных продукта, оценка порядка величины.
- Нет источника: добавки за малую площадь (+3 %) и крупный формат (+3 %). На сцене как
  «подтверждённые производителем» не называть.
- Раппорт обоев считается геометрически (раппорт берётся из карточки товара), не коэффициентом.

## 3. Демонстрационные сценарии (тесты `tests/service/test_corrections_scenarios.py`)

Комната 4×3 м, высота 2,5 м (пол 12 м², стены 35 м², потолок 12 м²), числа посчитаны вручную.

| # | сценарий | базовый | с условием | где объяснение |
|---|---|---|---|---|
| 1 | плитка 300×300, ванная: прямая и по диагонали | 13 уп. (12 × 1,07) | 14 уп. (12 × 1,12) | запас по раскладке в `explain` |
| 2 | финишная шпатлёвка, ровные и неровные стены | 4 мешка по 20 кг (2 мм) | 6 мешков (3 мм, Ceresit CT 225) | строка «Поправка [puttying…]» |
| 3 | краска, 1 и 2 слоя | 2 уп. по 2,5 л (4,7 л) | 4 уп. (9,4 л) | слои в формуле |
| 4 | краска на впитывающем основании | 4 уп. (9,4 л) | 6 уп. (9,4 × 1,43 = 13,44 л) | Tikkurila Prof Euro 7 |
| 5 | гипсовая штукатурка, ручная и машинная | 10 мешков по 30 кг (297,5 кг) | 12 мешков (× 1,18 = 351 кг) | Knauf MP 75 / Ротбанд |
| 6 | обои 0,53×10,05 м, потолок 2,2 м, без раппорта и с раппортом 0,64 м | 7 рулонов | 10 рулонов (полотно 2,56 м, 3 из рулона) | «с учётом раппорта…» |
| 7 | ламинат 12 м², прямая и диагональ | 7 уп. (12 × 1,05 / 2 = 6,3) | 8 уп. (12 × 1,20 / 2 = 7,2) | запас по раскладке (Quick-Step) |
"""
    return HEAD + body + scen


def main() -> int:
    out = ROOT / "docs" / "COEFFICIENTS.md"
    out.write_text(build(), encoding="utf-8")
    print(f"записано {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
